-- 20260917120000_fix_gating_bypass.sql
--
-- Closes a hole in 20260915120000_wayfinder_feature_gating.sql that let any
-- signed-in account grant itself paid features, permanently.
--
-- The root cause was the same in three places: the database had no idea which
-- objective opens which feature, or what each feature is gated behind. That
-- mapping lived only in src/data/objectives.js and src/data/featureCatalog.js,
-- so every check that needed it was either delegated to the client or skipped.
--
--   unlock_feature()      checked that the objective you named was finished,
--                         but never that it was the objective which opens the
--                         feature you asked for. Finish the easiest objective
--                         once, then claim anything.
--
--   complete_objective()  inserted whatever feature ids arrived in
--                         p_unlock_ids, with no validation whatsoever. This was
--                         the worst of the three: it did not even need a real
--                         objective/feature relationship to exist.
--
--   record_test_attempt() unlocked whatever p_feature_id it was given on a
--                         pass, and the client both grades the test and reports
--                         the score. The one-attempt rule was the only defence,
--                         which is no defence at all when one attempt buys a
--                         permanent grant on a paid feature.
--
-- The fix gives the database the mapping as reference data and re-checks every
-- claim against it. Behaviour for a legitimate user is unchanged: the same
-- objectives open the same features, and the same eight features can be tested
-- out of.
--
-- The three tables below mirror files in the app bundle and are regenerated by
-- scripts/gen-gating-seed.mjs. When those files change, run it and land the
-- output in a NEW migration; the seed replaces each table wholesale, so it is
-- safe to re-run.

-- Wrapped in a transaction so a failure part-way through cannot leave the
-- gate half-rebuilt — old functions with new tables, or vice versa. Postgres
-- DDL is transactional, so this rolls back cleanly.
begin;

