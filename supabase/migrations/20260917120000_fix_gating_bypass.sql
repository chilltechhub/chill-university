-- ─── unlock_feature() — now re-checks the gate AND the mapping ───────────────
--
-- Each method may only ever open the kind of feature it is actually a gate for:
--   'objective'    -> a 'locked' feature, and only one this objective opens
--   'plan'         -> a 'paid' feature, with a live plan
--   'experimental' -> an 'experimental' feature, with the opt-in on
-- An unknown feature id, or an 'open' one (nothing to unlock), is rejected
-- rather than quietly written.

create or replace function public.unlock_feature(
  p_feature_id   text,
  p_method       text,
  p_objective_id text default null
)
returns public.feature_unlocks
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row  public.feature_unlocks;
  v_gate text;
begin
  if auth.uid() is null then
    raise exception 'Not signed in.';
  end if;

  if p_method not in ('objective', 'plan', 'experimental') then
    raise exception 'Unlock method % cannot be claimed from the app.', p_method;
  end if;

  select gate into v_gate from public.feature_gates where feature_id = p_feature_id;

  if v_gate is null then
    raise exception 'There is no feature called %.', p_feature_id;
  end if;

  if v_gate = 'open' then
    raise exception 'Feature % is already open to everyone.', p_feature_id;
  end if;

  if p_method = 'objective' then
    if v_gate <> 'locked' then
      raise exception 'Feature % is behind the % gate, which finishing an objective does not open.', p_feature_id, v_gate;
    end if;
    if p_objective_id is null then
      raise exception 'An objective unlock has to say which objective.';
    end if;
    -- The check that was missing: this objective must be the one that opens
    -- this feature. Finishing any objective used to be enough to claim any.
    if not exists (
      select 1 from public.objective_unlocks
      where objective_id = p_objective_id and feature_id = p_feature_id
    ) then
      raise exception 'Objective % does not open %.', p_objective_id, p_feature_id;
    end if;
    if not exists (
      select 1 from public.user_objectives
      where user_id = auth.uid()
        and objective_id = p_objective_id
        and status = 'completed'
    ) then
      raise exception 'Objective % is not finished yet.', p_objective_id;
    end if;
  end if;

  if p_method = 'plan' then
    if v_gate <> 'paid' then
      raise exception 'Feature % is not a plan feature.', p_feature_id;
    end if;
    if not public.is_plan_active(auth.uid()) then
      raise exception 'That one needs an active plan.';
    end if;
  end if;

  if p_method = 'experimental' then
    if v_gate <> 'experimental' then
      raise exception 'Feature % is not an experimental feature.', p_feature_id;
    end if;
    if not exists (
      select 1 from public.profiles
      where id = auth.uid() and experimental_opt_in = true
    ) then
      raise exception 'Experimental features are switched off for this account.';
    end if;
  end if;

  insert into public.feature_unlocks (user_id, feature_id, method)
  values (auth.uid(), p_feature_id, p_method)
  on conflict (user_id, feature_id) do nothing;

  select * into v_row
  from public.feature_unlocks
  where user_id = auth.uid() and feature_id = p_feature_id;

  return v_row;
end;
$$;

comment on function public.unlock_feature(text, text, text) is
  'Grants a feature after re-checking both the gate it claims to have cleared and, for objective unlocks, that the named objective is the one that opens it.';

grant execute on function public.unlock_feature(text, text, text) to authenticated;

-- ─── complete_objective() — rewards now come from the mapping ────────────────
--
-- p_unlock_ids is kept so the existing client call still type-checks, but it
-- is deliberately IGNORED. What an objective opens is a property of the
-- objective, not something the caller gets a say in.

create or replace function public.complete_objective(
  p_objective_id text,
  p_unlock_ids   text[] default '{}'
)
returns public.user_objectives
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row public.user_objectives;
begin
  if auth.uid() is null then
    raise exception 'Not signed in.';
  end if;

  update public.user_objectives
     set status = 'completed', completed_at = now()
   where user_id = auth.uid()
     and objective_id = p_objective_id
     and status = 'active'
  returning * into v_row;

  if v_row.id is null then
    raise exception 'No active objective % to complete.', p_objective_id;
  end if;

  -- Whatever this objective actually opens, regardless of what was asked for.
  insert into public.feature_unlocks (user_id, feature_id, method)
  select auth.uid(), ou.feature_id, 'objective'
  from public.objective_unlocks ou
  join public.feature_gates fg on fg.feature_id = ou.feature_id
  where ou.objective_id = p_objective_id
    and fg.gate = 'locked'
  on conflict (user_id, feature_id) do nothing;

  return v_row;
end;
$$;

comment on function public.complete_objective(text, text[]) is
  'Completes the active objective and grants exactly the unlocks the mapping says it carries. p_unlock_ids is ignored and retained only for call compatibility.';

grant execute on function public.complete_objective(text, text[]) to authenticated;

-- ─── record_test_attempt() — only for things that can be tested out of ───────
--
-- Unchanged except for the allowlist check. The client still grades its own
-- test, which is tolerable for a 'locked' feature with one lifetime attempt,
-- and is not tolerable for anything else — so anything else is now refused
-- before an attempt is even recorded.

create or replace function public.record_test_attempt(
  p_feature_id text,
  p_score      int,
  p_total      int,
  p_pass_mark  int
)
returns public.feature_test_attempts
language plpgsql
security definer
set search_path = public
as $$
declare
  v_passed boolean;
  v_row    public.feature_test_attempts;
begin
  if auth.uid() is null then
    raise exception 'Not signed in.';
  end if;

  -- feature_tests only ever contains 'locked' features; the generator refuses
  -- to emit anything else.
  if not exists (select 1 from public.feature_tests where feature_id = p_feature_id) then
    raise exception 'Feature % cannot be tested out of.', p_feature_id;
  end if;

  if p_total <= 0 or p_score < 0 or p_score > p_total then
    raise exception 'Nonsense score: % of %.', p_score, p_total;
  end if;

  if p_pass_mark < ceil(p_total / 2.0) then
    raise exception 'A pass mark of % out of % is not a check.', p_pass_mark, p_total;
  end if;

  if exists (
    select 1 from public.feature_test_attempts
    where user_id = auth.uid() and feature_id = p_feature_id
  ) then
    raise exception 'This test has already been attempted. The objective path is the way in now.';
  end if;

  v_passed := p_score >= p_pass_mark;

  insert into public.feature_test_attempts (user_id, feature_id, passed, score, total)
  values (auth.uid(), p_feature_id, v_passed, p_score, p_total)
  returning * into v_row;

  if v_passed then
    insert into public.feature_unlocks (user_id, feature_id, method)
    values (auth.uid(), p_feature_id, 'test')
    on conflict (user_id, feature_id) do nothing;
  end if;

  return v_row;
end;
$$;

comment on function public.record_test_attempt(text, int, int, int) is
  'Records the single allowed test-out attempt for a testable feature and unlocks it on a pass. Refuses features that are not in feature_tests.';

grant execute on function public.record_test_attempt(text, int, int, int) to authenticated;

-- ─── clean up grants already handed out through the hole ─────────────────────
--
-- Any unlock whose method is 'objective' but which no completed objective of
-- that user actually opens was obtained through the bug. Unlocks earned by
-- 'test', 'plan' or an admin 'granted' are left alone.

delete from public.feature_unlocks fu
where fu.method = 'objective'
  and not exists (
    select 1
    from public.objective_unlocks ou
    join public.user_objectives uo
      on uo.objective_id = ou.objective_id
     and uo.user_id = fu.user_id
     and uo.status = 'completed'
    where ou.feature_id = fu.feature_id
  );

commit;
