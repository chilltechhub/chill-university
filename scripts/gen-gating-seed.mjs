// scripts/gen-gating-seed.mjs
//
// Emits the reference-data seed that the feature-gating SQL functions check
// against, read straight out of the files the app itself uses:
//
//   src/data/featureCatalog.js   -> feature_gates      (which gate each feature is behind)
//   src/data/objectives.js       -> objective_unlocks  (which objective opens which feature)
//   src/data/competencyTests.js  -> feature_tests      (what can be tested out of)
//
// Why this exists: before 20260917120000_fix_gating_bypass.sql the database
// had none of this. unlock_feature() checked that the objective you named was
// finished but never that it was the objective which opens the feature you
// asked for, and complete_objective() inserted whatever feature ids the client
// handed it. Either one let a free account grant itself paid features. The fix
// is only as good as this mapping, so it is generated rather than typed.
//
// Run it when objectives.js, featureCatalog.js or competencyTests.js change,
// and put the output in a NEW migration — the tables are replaced wholesale,
// so re-running a generated seed is safe and idempotent.
//
//   node scripts/gen-gating-seed.mjs
//
// It exits non-zero if the three files disagree with each other, which is the
// other half of the point: an objective that unlocks a paid feature, or a test
// bank for something that is not locked, is a data bug that would otherwise
// only surface as a hole in the gate.

import { readFile } from 'node:fs/promises';

// These data files have no imports of their own, so they can be evaluated
// directly as modules without pulling in the React Native graph.
async function load(path) {
  const src = await readFile(new URL(`../${path}`, import.meta.url), 'utf8');
  return import('data:text/javascript,' + encodeURIComponent(src));
}

const { FEATURES }   = await load('src/data/featureCatalog.js');
const { OBJECTIVES } = await load('src/data/objectives.js');
const tests          = (await load('src/data/competencyTests.js')).default;

const featureById = Object.fromEntries(FEATURES.map(f => [f.id, f]));
const problems = [];

const unlockPairs = [];
for (const o of OBJECTIVES) {
  for (const featureId of o.unlocks || []) {
    const f = featureById[featureId];
    if (!f) {
      problems.push(`objective "${o.id}" unlocks unknown feature "${featureId}"`);
      continue;
    }
    // An objective may only ever open a 'locked' feature. Letting one open a
    // 'paid' feature would make the paywall bypassable by design rather than
    // by bug.
    if (f.gate !== 'locked') {
      problems.push(`objective "${o.id}" unlocks "${featureId}", whose gate is "${f.gate}" and not "locked"`);
    }
    unlockPairs.push([o.id, featureId]);
  }
}

const testIds = Object.keys(tests);
for (const id of testIds) {
  const f = featureById[id];
  if (!f) {
    problems.push(`test bank "${id}" is not a feature in the catalog`);
    continue;
  }
  if (f.gate !== 'locked') {
    problems.push(`test bank "${id}" is for a "${f.gate}" feature; only "locked" ones may be tested out of`);
  }
}

if (problems.length) {
  console.error('Gating data is inconsistent:\n  - ' + problems.join('\n  - '));
  process.exit(1);
}

const rows = (list) => list.join(',\n');

console.log(`-- Generated by scripts/gen-gating-seed.mjs. Do not hand-edit.
-- ${FEATURES.length} features, ${unlockPairs.length} objective->feature unlocks, ${testIds.length} test banks.

delete from public.feature_gates;
insert into public.feature_gates (feature_id, gate) values
${rows(FEATURES.map(f => `  ('${f.id}', '${f.gate}')`))};

delete from public.objective_unlocks;
insert into public.objective_unlocks (objective_id, feature_id) values
${rows(unlockPairs.map(([o, f]) => `  ('${o}', '${f}')`))};

delete from public.feature_tests;
insert into public.feature_tests (feature_id) values
${rows(testIds.map(i => `  ('${i}')`))};`);
